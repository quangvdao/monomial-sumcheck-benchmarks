#!/usr/bin/env python3
"""Summarize independent Criterion runs and paired speedups."""

from __future__ import annotations

import argparse
import json
import math
import random
import statistics
from pathlib import Path


def quantile(values: list[float], probability: float) -> float:
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    position = probability * (len(ordered) - 1)
    lower = math.floor(position)
    upper = math.ceil(position)
    if lower == upper:
        return ordered[lower]
    weight = position - lower
    return ordered[lower] * (1 - weight) + ordered[upper] * weight


def bootstrap_median_ci(
    values: list[float], confidence: float = 0.99, samples: int = 10_000
) -> tuple[float, float]:
    rng = random.Random(0)
    draws = []
    for _ in range(samples):
        resample = [rng.choice(values) for _ in values]
        draws.append(statistics.median(resample))
    tail = (1 - confidence) / 2
    return quantile(draws, tail), quantile(draws, 1 - tail)


def summarize_values(values: list[float]) -> dict[str, float | int]:
    ci_low, ci_high = bootstrap_median_ci(values)
    return {
        "processes": len(values),
        "median": statistics.median(values),
        "p01": quantile(values, 0.01),
        "p99": quantile(values, 0.99),
        "median_ci99_low": ci_low,
        "median_ci99_high": ci_high,
    }


def load_runs(root: Path) -> dict[str, dict[str, float]]:
    runs: dict[str, dict[str, float]] = {}
    for run_dir in sorted(root.glob("run-*")):
        values: dict[str, float] = {}
        criterion = run_dir / "criterion"
        for estimates_path in criterion.glob("**/new/estimates.json"):
            benchmark = str(estimates_path.relative_to(criterion).parent.parent)
            estimates = json.loads(estimates_path.read_text())
            values[benchmark] = float(estimates["median"]["point_estimate"])
        if values:
            runs[run_dir.name] = values
    return runs


def parse_pair(text: str) -> tuple[str, str, str]:
    try:
        label, benchmarks = text.split("=", 1)
        baseline, optimized = benchmarks.split(",", 1)
    except ValueError as error:
        raise argparse.ArgumentTypeError(
            "pair must have the form LABEL=BASELINE,OPTIMIZED"
        ) from error
    return label, baseline, optimized


def human_time(nanoseconds: float) -> tuple[float, str]:
    if nanoseconds >= 1_000_000:
        return nanoseconds / 1_000_000, "ms"
    if nanoseconds >= 1_000:
        return nanoseconds / 1_000, "us"
    return nanoseconds, "ns"


def latex_escape(value: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "_": r"\_",
        "%": r"\%",
        "&": r"\&",
        "#": r"\#",
        "{": r"\{",
        "}": r"\}",
    }
    return "".join(replacements.get(character, character) for character in value)


def latex(summary: dict[str, object]) -> str:
    lines = [
        "% Generated by scripts/summarize.py; do not edit by hand.",
    ]
    warnings = summary["warnings"]
    assert isinstance(warnings, list)
    for warning in warnings:
        lines.append(f"% NOT PAPER READY: {warning}")
    lines.extend(
        [
            r"\begin{tabular}{@{}lrrrrr@{}}",
            r"\toprule",
            r"Benchmark & Processes & Median & 99\% CI & p01 & p99 \\",
            r"\midrule",
        ]
    )
    benchmarks = summary["benchmarks"]
    assert isinstance(benchmarks, dict)
    for name, stats_value in benchmarks.items():
        stats = stats_value
        assert isinstance(stats, dict)
        median, unit = human_time(float(stats["median"]))
        divisor = {"ns": 1.0, "us": 1_000.0, "ms": 1_000_000.0}[unit]
        low = float(stats["median_ci99_low"]) / divisor
        high = float(stats["median_ci99_high"]) / divisor
        p01 = float(stats["p01"]) / divisor
        p99 = float(stats["p99"]) / divisor
        lines.append(
            f"{latex_escape(name)} & {stats['processes']} & {median:.3f} {unit} & "
            f"[{low:.3f}, {high:.3f}] {unit} & {p01:.3f} {unit} & {p99:.3f} {unit} \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular}"])

    pairs = summary["pairs"]
    assert isinstance(pairs, dict)
    if pairs:
        lines.extend(
            [
                "",
                r"\begin{tabular}{@{}lrrrrr@{}}",
                r"\toprule",
                r"Comparison & Processes & Median & 99\% CI & p01 & p99 \\",
                r"\midrule",
            ]
        )
        for label, stats_value in pairs.items():
            stats = stats_value
            assert isinstance(stats, dict)
            lines.append(
                f"{latex_escape(label)} & {stats['processes']} & {stats['median']:.3f}x & "
                f"[{stats['median_ci99_low']:.3f}, {stats['median_ci99_high']:.3f}]x & "
                f"{stats['p01']:.3f}x & {stats['p99']:.3f}x \\\\"
            )
        lines.extend([r"\bottomrule", r"\end{tabular}"])
    return "\n".join(lines) + "\n"


def markdown(summary: dict[str, object]) -> str:
    lines = [
        "# Benchmark summary",
        "",
        "Times are process-level Criterion medians. Intervals are 99% bootstrap",
        "confidence intervals for the median across independent processes.",
        "The p01 and p99 columns are empirical process-level quantiles.",
        "",
    ]
    warnings = summary["warnings"]
    assert isinstance(warnings, list)
    if warnings:
        lines.extend(["> **Not ready for paper use.** " + " ".join(warnings), ""])
    lines.extend([
        "| Benchmark | Processes | Median | 99% CI | p01 | p99 |",
        "|---|---:|---:|---:|---:|---:|",
    ])
    benchmarks = summary["benchmarks"]
    assert isinstance(benchmarks, dict)
    for name, stats_value in benchmarks.items():
        stats = stats_value
        assert isinstance(stats, dict)
        median, unit = human_time(float(stats["median"]))
        low, _ = human_time(float(stats["median_ci99_low"]))
        high, _ = human_time(float(stats["median_ci99_high"]))
        p01, _ = human_time(float(stats["p01"]))
        p99, _ = human_time(float(stats["p99"]))
        lines.append(
            f"| {name} | {stats['processes']} | {median:.3f} {unit} | "
            f"[{low:.3f}, {high:.3f}] {unit} | {p01:.3f} {unit} | {p99:.3f} {unit} |"
        )

    pairs = summary["pairs"]
    assert isinstance(pairs, dict)
    if pairs:
        lines.extend(
            [
                "",
                "## Paired speedups",
                "",
                "| Pair | Processes | Median | 99% CI | p01 | p99 |",
                "|---|---:|---:|---:|---:|---:|",
            ]
        )
        for label, stats_value in pairs.items():
            stats = stats_value
            assert isinstance(stats, dict)
            lines.append(
                f"| {label} | {stats['processes']} | {stats['median']:.3f}x | "
                f"[{stats['median_ci99_low']:.3f}, {stats['median_ci99_high']:.3f}]x | "
                f"{stats['p01']:.3f}x | {stats['p99']:.3f}x |"
            )
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("run_directory", type=Path)
    parser.add_argument("--pair", action="append", default=[], type=parse_pair)
    parser.add_argument("--json", type=Path)
    parser.add_argument("--markdown", type=Path)
    parser.add_argument("--latex", type=Path)
    parser.add_argument(
        "--min-processes",
        type=int,
        default=20,
        help="minimum independent processes required for paper-ready output",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    runs = load_runs(args.run_directory)
    if not runs:
        raise SystemExit("no process runs found")

    benchmark_values: dict[str, list[float]] = {}
    for values in runs.values():
        for benchmark, estimate in values.items():
            benchmark_values.setdefault(benchmark, []).append(estimate)

    result: dict[str, object] = {
        "schema": 1,
        "run_directory": str(args.run_directory),
        "benchmarks": {
            name: summarize_values(values)
            for name, values in sorted(benchmark_values.items())
        },
        "pairs": {},
        "warnings": [],
    }

    minimum = min(len(values) for values in benchmark_values.values())
    if minimum < args.min_processes:
        result["warnings"] = [
            f"At least one benchmark has only {minimum} independent process(es); "
            f"the methodology requires {args.min_processes}."
        ]

    pairs: dict[str, object] = {}
    for label, baseline, optimized in args.pair:
        ratios = []
        for values in runs.values():
            if baseline in values and optimized in values:
                ratios.append(values[baseline] / values[optimized])
        if not ratios:
            available = "\n".join(sorted(benchmark_values))
            raise SystemExit(
                f"pair {label} matched no complete process runs; available benchmarks:\n{available}"
            )
        pairs[label] = {
            "baseline": baseline,
            "optimized": optimized,
            **summarize_values(ratios),
        }
    result["pairs"] = pairs

    json_text = json.dumps(result, indent=2) + "\n"
    markdown_text = markdown(result)
    latex_text = latex(result)
    if args.json:
        args.json.write_text(json_text)
    if args.markdown:
        args.markdown.write_text(markdown_text)
    if args.latex:
        args.latex.write_text(latex_text)
    if not args.json and not args.markdown and not args.latex:
        print(markdown_text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
